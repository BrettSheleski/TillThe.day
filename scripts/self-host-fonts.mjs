// Copies the theme fonts from the @fontsource packages into the site, so
// they're served from here rather than Google Fonts. Writes:
//   assets/fonts/*.woff2          the font files
//   assets/fonts/LICENSE-*.txt    each font's license (required by the OFL)
//   _sass/_fonts.scss             the @font-face rules
//
// Run with `npm run fonts` after changing FONTS. Commit the results.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");

// Package name → the weights the themes use (see _sass/themes/*/_theme.scss)
const FONTS = {
  "inter": [400, 500, 600, 700, 800],
  "fredoka": [400, 500, 600, 700],
  "share-tech-mono": [400],
  "great-vibes": [400],
  "cormorant-garamond": [400, 600, 700],
  "baloo-2": [400, 600, 700],
  "mountains-of-christmas": [400, 700],
  "lora": [400, 600],
  "quicksand": [400, 600, 700],
  "pacifico": [400],
  "orbitron": [500, 700],
  "press-start-2p": [400],
  "jost": [300, 400, 500],
};

// Latin covers English and most Western European languages; browsers only
// download a subset when the page uses characters in its unicode-range.
const SUBSETS = ["latin", "latin-ext"];

const fontsDir = path.join(root, "assets", "fonts");
fs.rmSync(fontsDir, { recursive: true, force: true });
fs.mkdirSync(fontsDir, { recursive: true });

const rules = [];
for (const [pkg, weights] of Object.entries(FONTS)) {
  const pkgDir = path.join(root, "node_modules", "@fontsource", pkg);
  fs.copyFileSync(path.join(pkgDir, "LICENSE"), path.join(fontsDir, `LICENSE-${pkg}.txt`));

  for (const weight of weights) {
    const css = fs.readFileSync(path.join(pkgDir, `${weight}.css`), "utf8");
    // Each block: /* <name> */ @font-face { ... }
    for (const [, name, body] of css.matchAll(/\/\* ([\w-]+) \*\/\s*@font-face \{([\s\S]*?)\}/g)) {
      const subset = SUBSETS.find((s) => name === `${pkg}-${s}-${weight}-normal`);
      if (!subset) continue;
      const family = body.match(/font-family: '([^']+)'/)[1];
      const range = body.match(/unicode-range: ([^;]+);/)?.[1];
      const file = `${name}.woff2`;
      fs.copyFileSync(path.join(pkgDir, "files", file), path.join(fontsDir, file));
      rules.push(
        [
          "@font-face {",
          `  font-family: "${family}";`,
          "  font-style: normal;",
          `  font-weight: ${weight};`,
          "  font-display: swap;",
          `  src: url("../fonts/${file}") format("woff2");`,
          range ? `  unicode-range: ${range};` : null,
          "}",
        ].filter(Boolean).join("\n")
      );
    }
  }
}

const header = [
  "// Theme fonts, served from this site (assets/fonts/).",
  "// Generated by scripts/self-host-fonts.mjs; don't edit by hand.",
  "",
].join("\n");
fs.writeFileSync(path.join(root, "_sass", "_fonts.scss"), header + rules.join("\n\n") + "\n");

const files = fs.readdirSync(fontsDir).filter((f) => f.endsWith(".woff2"));
const kb = files.reduce((sum, f) => sum + fs.statSync(path.join(fontsDir, f)).size, 0) / 1024;
console.log(`${rules.length} @font-face rules, ${files.length} font files (${kb.toFixed(0)} KB total)`);
